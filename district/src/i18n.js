/** 某座位在各語言的預設政黨名稱（用來判斷使用者有沒有改過名字） */
export function defaultPartyNames(index) {
  return Object.values(DICTS).map((d) => d[`party.${index}`]);
}

/**
 * 政黨顯示名稱：沒改過名字（空白，或等於任一語言的預設名）就顯示目前語言的預設名；改過的照原樣顯示。
 */
export function partyDisplayName(name, index) {
  const trimmed = (name || "").trim();
  if (!trimmed || defaultPartyNames(index % 6).includes(trimmed)) return t(`party.${index % 6}`);
  return trimmed;
}
