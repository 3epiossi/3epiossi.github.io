/**
 * 難度分級：5 級。第 5 級是完整的新引擎（expectimax + Star1 剪枝 + 學出來的評估，吃滿設定的思考時間，迭代加深）；
 * 下面幾級用固定層數與隨機失誤（eps）削弱，第 1 級只會隨機走合法步。
 *   kind "random"  隨機合法步
 *   depth          固定層數（棋力與電腦快慢無關）；沒有 depth = 依思考時間迭代加深
 *   eps            每一步改走隨機合法步的機率（模擬失誤）
 *
 * 相鄰兩級的實測勝率（上一級贏；tests/level-ladder.js，每對手同一串骰子、交換黑白；目標約 80%，±5% 以內）：
 *   2 級對 1 級 84.1%（320 局）、3 對 2 82.8%（320 局）、4 對 3 75.0%（320 局）、
 *   5 對 4 81.7%（120 局，每步 0.5 秒＝預設思考時間，6 條平行；誤差 ±6.9%）。
 * 骰子運氣成分大，強的幾級之間的差距很小（3 層對 2 層只有 61%，80 局），所以沒有硬湊第 6 級：試過在 4 級與完整引擎之間放
 * 「固定 2 層」一級，它對 4 級贏 76%（在目標範圍內），但完整引擎（0.5 秒）對它只有 54%（120 局；每步 1 秒的版本 52%，96 局；
 * 兩個都是電腦負載很高時量的），到不了目標，所以拿掉，總共 5 級。最高級按時間搜，實測數字會隨機器快慢與負載而變。
 */
export const LEVELS = [
  { id: 1, kind: "random" },
  { id: 2, depth: 1, eps: 0.65 },
  { id: 3, depth: 1, eps: 0.35 },
  { id: 4, depth: 1, eps: 0.15 },
  { id: 5 }                         // 完整引擎，吃滿設定的思考時間（迭代加深）
];
export const MAX_LEVEL = LEVELS.length;
export const clampLevel = (n) => Math.min(MAX_LEVEL, Math.max(1, Math.round(Number(n)) || MAX_LEVEL));
export const isTimedLevel = (n) => { const c = LEVELS[clampLevel(n) - 1]; return c.kind !== "random" && !c.depth; };

/**
 * 舊版 v1~v5 演算法設定對應到新等級，依實測棋力最接近的一級（tests/arena.js，同一串骰子、交換黑白，勝率是舊演算法的）：
 *   v1：對隨機 77.5%（80 局）、對 2 級 31.3%（80 局）             => 2 級
 *   v2：對隨機 71.3%（80 局）、對 2 級 30.0%、對 3 級 10.0%（各 80 局） => 2 級
 *   v3：對 3 級 51.7%、對 4 級 25.0%（各 60 局）                   => 3 級
 *   v4：對 3 級 60.0%、對 4 級 33.3%（各 60 局）                   => 3 級
 *   v5：對 4 級 35.4%（48 局）、對新引擎固定 2 層 17.0%（200 局）   => 4 級
 * 舊版最強的 v5 只相當於新的第 4 級；新的第 5 級（完整引擎，0.5 秒）對 v5 贏 86.3%（69 / 80 局，±7.5%）。
 */
export const LEGACY_ALGO_LEVEL = { v1: 2, v2: 2, v3: 3, v4: 3, v5: 4 };
export const levelFromAlgo = (algo) => LEGACY_ALGO_LEVEL[algo] ?? MAX_LEVEL;
